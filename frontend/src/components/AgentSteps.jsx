/**
 * AgentSteps.jsx — AI Agent Activity timeline + AI Recovery Analysis
 * Phase 4: Clear tool→human-readable mapping, explanation display, no fabrication
 */

const TOOL_MAP = {
  get_payment: {
    label: 'Payment Retrieved',
    meta:  'Payment information retrieved from the recovery dataset',
    icon:  '📄',
  },
  check_payment_eligibility: {
    label: 'Eligibility Checked',
    meta:  'Deterministic recovery eligibility policy evaluated',
    icon:  '🛡',
  },
  predict_recovery: {
    label: 'Recovery Prediction',
    meta:  'ML model computed recovery probability',
    icon:  '◎',
  },
  calculate_payment_revenue_risk: {
    label: 'Revenue Risk Analysis',
    meta:  'Revenue at risk and expected recovery value calculated',
    icon:  '💰',
  },
  make_payment_recovery_decision: {
    label: 'Recovery Decision',
    meta:  'Priority and recommended action generated by decision engine',
    icon:  '⚡',
  },
}

function toolInfo(toolName) {
  return TOOL_MAP[toolName] || {
    label: toolName.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
    meta:  `Tool executed: ${toolName}`,
    icon:  '⚙',
  }
}

function agentStatusChip(status) {
  if (status === 'complete') {
    return { label: '✓ Complete', className: 'chip chip--success' }
  }
  if (status === 'max_iterations_reached') {
    return { label: '⚠ Iteration limit', className: 'chip chip--warning' }
  }
  if (status === 'provider_error') {
    return { label: '✕ Provider error', className: 'chip chip--warning' }
  }
  return { label: status || 'Unknown', className: 'chip chip--neutral' }
}

export function AgentSteps({ agent }) {
  if (!agent) return null

  const { status, iterations, actions = [], errors = [], explanation } = agent
  const chip = agentStatusChip(status)

  return (
    <div className="card" aria-label="AI Agent Activity">
      {/* Header */}
      <div className="card-header">
        <div className="card-icon card-icon--indigo" aria-hidden="true">🤖</div>
        <span className="card-title">AI Agent Activity</span>
        <div className="agent-chips">
          <span className={chip.className}>{chip.label}</span>
          {iterations != null && (
            <span className="chip chip--neutral">
              {iterations} iteration{iterations !== 1 ? 's' : ''}
            </span>
          )}
        </div>
      </div>

      {/* Tool timeline */}
      {actions.length > 0 && (
        <div style={{ marginBottom: 'var(--space-5)' }}>
          <div className="section-label">Tool Execution Trace</div>
          <div className="tool-timeline" role="list">
            {actions.map((action, i) => {
              const info = toolInfo(action.tool)
              return (
                <div className="timeline-step" key={i} role="listitem">
                  <div className="timeline-dot timeline-dot--complete" aria-hidden="true">
                    {info.icon}
                  </div>
                  <div className="timeline-content">
                    <div className="timeline-tool">{info.label}</div>
                    <div className="timeline-meta">{info.meta}</div>
                  </div>
                </div>
              )
            })}

            {/* Final step */}
            <div className="timeline-step" role="listitem">
              <div className="timeline-dot timeline-dot--final" aria-hidden="true">✦</div>
              <div className="timeline-content">
                <div className="timeline-tool">AI Explanation</div>
                <div className="timeline-meta">Agent generated operational recovery explanation</div>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Agent errors */}
      {errors.length > 0 && (
        <div style={{ marginBottom: 'var(--space-4)' }} role="alert">
          {errors.map((err, i) => (
            <div key={i} style={{
              padding: 'var(--space-3) var(--space-4)',
              background: 'var(--color-warning-bg)',
              border: '1px solid var(--color-warning-border)',
              borderRadius: 'var(--radius-md)',
              fontSize: 12,
              color: 'var(--color-warning)',
              marginBottom: 'var(--space-2)',
            }}>
              ⚠ Agent warning: {err}
            </div>
          ))}
        </div>
      )}

      {/* AI Recovery Analysis / Explanation */}
      <div className="agent-explanation">
        <div className="agent-explanation-header">
          <div className="agent-explanation-label">AI Recovery Analysis</div>
          <span className="agent-explanation-badge">AI-GENERATED</span>
        </div>
        {explanation ? (
          <>
            <div style={{ fontSize: 11, color: 'var(--color-text-muted)', marginBottom: 'var(--space-4)' }}>
              AI-generated explanation based on verified recovery analysis from deterministic tools
            </div>
            <div className="explanation-text">{explanation}</div>
          </>
        ) : (
          <div className="explanation-text" style={{ color: 'var(--color-text-muted)', fontStyle: 'italic' }}>
            Recovery analysis is available from the deterministic decision engine.
          </div>
        )}
      </div>
    </div>
  )
}
